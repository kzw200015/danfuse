-- 由 scripts/schema.sh 在执行完迁移的库上运行，按表输出 CREATE 语句：每张表一条 CREATE TABLE，约束写在表内，
-- 不属于约束的索引紧跟在表后面；另外输出不属于标识列的序列和视图。
-- 输出为一列文本，各对象之间空一行。表按外键的依赖排序，被引用的表在前、同一层按名称排，整个文件可以直接执行：
-- schema.sh 会把它执行到另一个空库，比对两边的 pg_dump，这里漏了迁移里的任何对象（函数、触发器、注释等）都会报错。
\pset format unaligned
\pset tuples_only on
\pset recordsep '\n\n'

WITH RECURSIVE
tables AS (
	SELECT c.oid, c.relname
	FROM pg_class c
	WHERE c.relnamespace = 'public'::regnamespace AND c.relkind IN ('r', 'p') AND c.relname <> 'goose_db_version'
),
-- 外键依赖的层级：不引用别的表为 0，否则比它引用的表中最深的一层再深一层（自引用不算）
fk AS (
	SELECT DISTINCT conrelid AS child, confrelid AS parent
	FROM pg_constraint
	WHERE contype = 'f' AND conrelid IN (SELECT oid FROM tables) AND conrelid <> confrelid
),
depth AS (
	SELECT oid, 0 AS level, ARRAY[oid] AS path FROM tables
	UNION ALL
	SELECT fk.child, d.level + 1, d.path || fk.child
	FROM depth d
	JOIN fk ON fk.parent = d.oid
	WHERE fk.child <> ALL (d.path)
),
cols AS (
	SELECT a.attrelid, a.attnum, a.attname, format_type(a.atttypid, a.atttypmod) AS type,
		concat_ws(' ',
			CASE a.attidentity WHEN 'a' THEN 'GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY' END,
			CASE a.attgenerated
				WHEN 's' THEN 'GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid, true) || ') STORED'
				WHEN 'v' THEN 'GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid, true) || ') VIRTUAL'
			END,
			-- 标识列隐含 NOT NULL
			CASE WHEN a.attnotnull AND a.attidentity = '' THEN 'NOT NULL' END,
			CASE WHEN a.attgenerated = '' AND d.adbin IS NOT NULL THEN 'DEFAULT ' || pg_get_expr(d.adbin, d.adrelid, true) END
		) AS extra
	FROM pg_attribute a
	JOIN tables t ON t.oid = a.attrelid
	LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
	WHERE a.attnum > 0 AND NOT a.attisdropped
),
-- 列名、类型各自按本表最长的对齐
col_lines AS (
	SELECT attrelid, attnum,
		rtrim(rpad(quote_ident(attname), max(length(quote_ident(attname))) OVER w) || ' '
			|| rpad(type, max(length(type)) OVER w) || ' ' || extra) AS line
	FROM cols
	WINDOW w AS (PARTITION BY attrelid)
),
-- 主键、唯一、检查、外键、排除约束；PG18 起 NOT NULL 也记在 pg_constraint（contype = 'n'），已写在列上
con_lines AS (
	SELECT conrelid AS attrelid,
		row_number() OVER (PARTITION BY conrelid
			ORDER BY array_position(ARRAY['p', 'u', 'c', 'f', 'x']::"char"[], contype), conname) AS ord,
		'CONSTRAINT ' || quote_ident(conname) || ' ' || pg_get_constraintdef(oid, true) AS line
	FROM pg_constraint
	WHERE conrelid IN (SELECT oid FROM tables) AND contype <> 'n'
),
table_ddl AS (
	SELECT t.relname AS name, (SELECT max(level) FROM depth WHERE depth.oid = t.oid) AS level,
		'CREATE TABLE ' || quote_ident(t.relname) || E' (\n'
		|| (SELECT string_agg('    ' || line, E',\n' ORDER BY k1, k2) FROM (
			SELECT 1 AS k1, attnum::bigint AS k2, line FROM col_lines WHERE attrelid = t.oid
			UNION ALL
			SELECT 2, ord, line FROM con_lines WHERE attrelid = t.oid
		) l)
		|| E'\n);'
		|| coalesce((
			SELECT E'\n' || string_agg(replace(replace(pg_get_indexdef(i.indexrelid, 0, true), ' ON public.', ' ON '), ' USING btree', '') || ';', E'\n'
				ORDER BY ic.relname)
			FROM pg_index i
			JOIN pg_class ic ON ic.oid = i.indexrelid
			WHERE i.indrelid = t.oid
				AND NOT EXISTS (SELECT FROM pg_constraint c WHERE c.conindid = i.indexrelid AND c.conrelid = t.oid)
		), '') AS ddl
	FROM tables t
),
-- 标识列自带的序列不单独输出
seq_ddl AS (
	SELECT s.sequencename AS name,
		'CREATE SEQUENCE ' || quote_ident(s.sequencename)
		|| CASE WHEN s.data_type <> 'bigint'::regtype THEN ' AS ' || format_type(s.data_type, NULL) ELSE '' END
		|| CASE WHEN s.increment_by <> 1 THEN ' INCREMENT BY ' || s.increment_by ELSE '' END
		|| CASE WHEN s.start_value <> 1 THEN ' START WITH ' || s.start_value ELSE '' END
		|| CASE WHEN s.cycle THEN ' CYCLE' ELSE '' END
		|| ';' AS ddl
	FROM pg_sequences s
	WHERE s.schemaname = 'public'
		AND NOT EXISTS (SELECT FROM pg_depend d
			WHERE d.objid = format('public.%I', s.sequencename)::regclass AND d.deptype = 'i')
),
view_ddl AS (
	SELECT c.relname AS name,
		CASE c.relkind WHEN 'v' THEN 'CREATE VIEW ' ELSE 'CREATE MATERIALIZED VIEW ' END
		|| quote_ident(c.relname) || E' AS\n' || rtrim(pg_get_viewdef(c.oid, true), ';') || ';' AS ddl
	FROM pg_class c
	WHERE c.relnamespace = 'public'::regnamespace AND c.relkind IN ('v', 'm')
)
SELECT ddl FROM (
	SELECT 1 AS k, 0 AS level, name, ddl FROM seq_ddl
	UNION ALL SELECT 2, level, name, ddl FROM table_ddl
	UNION ALL SELECT 3, 0, name, ddl FROM view_ddl
) o
ORDER BY k, level, name;
